def detect_country(node):
    """Return (flag_emoji, russian_name) or (None, None) if unknown."""
    name = str(node.get("ps") or node.get("name") or "")
    host = str(node.get("host") or "")
    text = f"{name} {host}".lower()

    for kws, flag, ru in CITY_KEYWORDS:
        if any(kw in text for kw in kws):
            return flag, ru

    for kws, flag, ru in NAME_KEYWORDS:
        if any(kw in text for kw in kws):
            return flag, ru

    for code, (flag, ru) in COUNTRIES.items():
        if flag in name:
            return flag, ru

    labels = host.lower().split(".")
    for label in labels:
        m = re.match(r"^([a-z]{2})[\d\-_]*$", label)
        if m and m.group(1) in COUNTRIES:
            return COUNTRIES[m.group(1)]

    for word in re.findall(r"(?<![a-z])[a-z]{2}(?![a-z])", text):
        if word in COUNTRIES:
            return COUNTRIES[word]

    return None, None
